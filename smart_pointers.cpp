//     ✅ Автоматического управления памятью (умные указатели)


#include <memory>
#include <iostream>

class MyClass {
public:
    MyClass() { std::cout << "MyClass created\n"; }
    ~MyClass() { std::cout << "MyClass destroyed\n"; }
    void speak() { std::cout << "Hello from MyClass\n"; }
};

// ============================================================================
// UNIQUE_PTR - ЕДИНСТВЕННЫЙ ХОЗЯИН
// ============================================================================

/*
ЗАЧЕМ ИСПОЛЬЗОВАТЬ НА ПРАКТИКЕ:
- Когда у объекта ОДИН четкий владелец
- Минимальные затраты памяти (как обычный указатель)
- Не нужно думать об удалении - само удалится
- Отлично для временных объектов, фабрик, исключительного владения
- ИСПОЛЬЗУЙТЕ ПО УМОЛЧАНИЮ, если не нужны другие варианты!

ПРЕИМУЩЕСТВА:
✅ Один владелец в любой момент времени
✅ Автоматическое освобождение памяти  
✅ Минимальные накладные расходы (как "сырой" указатель)

НЕДОСТАТКИ:
❌ Нельзя копировать, только перемещать
*/

void demo_unique_ptr() {
    // unique_ptr - как единственный ключ от квартиры
    // Только один человек может им владеть в каждый момент
    std::unique_ptr<MyClass> ptr1(new MyClass());
    
    // ❌ Нельзя скопировать - как нельзя сделать копию ключа
    // std::unique_ptr<MyClass> ptr2 = ptr1; // ОШИБКА! Компилятор не пропустит
    
    // ✅ Можно передать ключ другому (переместить)
    std::unique_ptr<MyClass> ptr3 = std::move(ptr1); // Теперь ptr3 владеет объектом
    ptr3->speak(); // Можем использовать объект
    
    // При выходе из функции объект автоматически удалится
    // Как будто вы вышли из квартиры и дверь закрылась за собой
}

// ============================================================================
// SHARED_PTR - ОБЩАЯ СОБСТВЕННОСТЬ  
// ============================================================================

/*
ЗАЧЕМ ИСПОЛЬЗОВАТЬ НА ПРАКТИКЕ:
- Когда объектом владеют НЕСКОЛЬКО частей программы
- Для кэшей, где данные используются в разных местах
- Когда непонятно, кто должен удалять объект последним
- Для разделяемых ресурсов (соединения, конфигурации, менеджеры)

ПРЕИМУЩЕСТВА:
✅ Множество владельцев
✅ Счетчик ссылок (знает, сколько владельцев)
✅ Автоматическое удаление при count = 0

НЕДОСТАТКИ:
⚠️ Накладные расходы на счетчик ссылок
⚠️ Возможность циклических ссылок (когда два объекта держат друг друга)
*/

void demo_shared_ptr() {
    // shared_ptr - как общий доступ к документу Google Docs
    // Несколько людей могут работать с одним документом
    std::shared_ptr<MyClass> ptr1 = std::make_shared<MyClass>();
    std::cout << "Count: " << ptr1.use_count() << "\n"; // 1 - один человек смотрит
    
    {// блок с областью видимости
        // Новый пользователь открыл документ
        std::shared_ptr<MyClass> ptr2 = ptr1; // Копирование разрешено
        std::cout << "Count: " << ptr1.use_count() << "\n"; // 2 - уже два человека
        ptr2->speak(); // Оба могут использовать объект
    } // ptr2 вышел из области - один пользователь закрыл документ
    
    std::cout << "Count: " << ptr1.use_count() << "\n"; // 1 - остался один
    
    // Когда все выйдут (count = 0) - документ удалится автоматически
}

// ============================================================================
// WEAK_PTR - "СМОТРЕЛКА" БЕЗ ПРАВА ВЛАДЕНИЯ
// ============================================================================

/*
ЗАЧЕМ ИСПОЛЬЗОВАТЬ НА ПРАКТИКЕ:
- ✅ РАЗРУШАТЬ ЦИКЛИЧЕСКИЕ ССЫЛКИ (самая важная задача!)
- ✅ Кэширование - хранить ссылки на объекты, но не мешать их удалению
- ✅ Наблюдатели - следить за объектами, которые могут быть удалены
- ✅ Временные ссылки - когда не хотим продлевать жизнь объекту

КАК РАБОТАЕТ:
- weak_ptr - как окно в чужую квартиру
- Можете посмотреть, есть ли кто дома, но не можете войти
- Не увеличивает счетчик ссылок shared_ptr
- Может "превратиться" во временный shared_ptr через метод lock()
*/

void demo_weak_ptr() {
    // Создаем хозяина (shared_ptr) - того, кто реально владеет объектом
    std::shared_ptr<MyClass> shared = std::make_shared<MyClass>();
    
    // Создаем "наблюдателя" (weak_ptr) - того, кто только смотрит
    std::weak_ptr<MyClass> weak = shared;
    
    std::cout << "Shared count: " << shared.use_count() << "\n"; // 1
    // weak_ptr НЕ увеличивает счетчик! Он просто "смотрит" со стороны
    
    std::cout << "Weak expired: " << weak.expired() << "\n"; // false - объект жив
    
    // Чтобы войти в квартиру, нужно попросить временный ключ у weak_ptr
    if (auto temp = weak.lock()) { // Получаем временный shared_ptr
        temp->speak(); // Теперь можем использовать объект
        std::cout << "Temp count: " << temp.use_count() << "\n"; // 2 - есть временный доступ
    } // temp уничтожается - счетчик снова становится 1
    
    // Хозяин ушел и забрал объект (удалил shared_ptr)
    shared.reset();
    
    std::cout << "Weak expired: " << weak.expired() << "\n"; // true - объект умер
    
    if (auto temp = weak.lock()) {
        // Сюда не попадем - объект уже удален
        std::cout << "This won't execute\n";
    } else {
        std::cout << "Object no longer exists\n"; // Сообщим, что объекта нет
    }
}

// ============================================================================
// ПРИМЕР ПРОБЛЕМЫ, КОТОРУЮ РЕШАЕТ WEAK_PTR
// ============================================================================

/*
ПРОБЛЕМА ЦИКЛИЧЕСКИХ ССЫЛОК:
- Когда два shared_ptr держат друг друга
- Они никогда не удалятся, потому что счетчики никогда не станут 0
- ПРОИСХОДИТ УТЕЧКА ПАМЯТИ!

РЕШЕНИЕ:
- Заменить одну из ссылок на weak_ptr
- weak_ptr не увеличивает счетчик, поэтому цикл разрывается
*/

struct Node {
    std::string name;
    
    // ❌ ПРОБЛЕМА: циклическая ссылка (УТЕЧКА ПАМЯТИ!)
    // std::shared_ptr<Node> partner; 
    // Два узла держат друг друга через shared_ptr
    // Node1 содержит shared_ptr на Node2 (count Node2 = 1 + 1 = 2)
    // Node2 содержит shared_ptr на Node1 (count Node1 = 1 + 1 = 2)
    // При удалении внешних shared_ptr: count становится 1, но не 0!
    // ОБЪЕКТЫ НИКОГДА НЕ УДАЛЯТСЯ!
    
    // ✅ РЕШЕНИЕ: weak_ptr - наблюдает, но не владеет
    std::weak_ptr<Node> partner;     
    // Node1 содержит weak_ptr на Node2 (count Node2 = 1)
    // Node2 содержит weak_ptr на Node1 (count Node1 = 1)
    // При удалении внешних shared_ptr: count становится 0
    // ОБЪЕКТЫ КОРРЕКТНО УДАЛЯЮТСЯ!
    
    Node(const std::string& n) : name(n) {}
    ~Node() { std::cout << name << " destroyed\n"; }
};

void demo_cyclic_reference() {
    auto node1 = std::make_shared<Node>("Node1");
    auto node2 = std::make_shared<Node>("Node2");
    
    // Устанавливаем взаимные ссылки
    node1->partner = node2; // Node2: count остается 1 (только node2 владеет)
    node2->partner = node1; // Node1: count остается 1 (только node1 владеет)
    
    // При выходе из функции:
    // node1 удаляется -> count Node1 становится 0 -> Node1 удаляется
    // node2 удаляется -> count Node2 становится 0 -> Node2 удаляется
    // ВСЕ КОРРЕКТНО УДАЛЯЕТСЯ благодаря weak_ptr!
}

